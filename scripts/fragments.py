"""Generates components/ui/PaperCollage.tsx — the torn paper layers behind the
hero cut-out. Run: python3 scripts/fragments.py"""
import math, random

def torn_quad(corners, seed, amp=28.0, step=26.0):
    """Walk a quadrilateral, perturbing perpendicular to each edge. Amplitude
    has to be large relative to the viewBox or the edge reads as straight once
    the SVG is scaled up to the hero's width."""
    rnd = random.Random(seed)
    pts = []
    n = len(corners)
    for i in range(n):
        x0, y0 = corners[i]
        x1, y1 = corners[(i + 1) % n]
        dx, dy = x1 - x0, y1 - y0
        length = math.hypot(dx, dy)
        ux, uy = dx / length, dy / length
        nx, ny = -uy, ux
        t, phase = 0.0, rnd.uniform(0, math.tau)
        while t < length:
            t = min(length, t + rnd.uniform(step * 0.5, step * 1.8))
            f = t / length
            wander = math.sin(phase + f * 7.0) * amp * 0.75
            swell = math.sin(phase * 1.7 + f * 2.3) * amp * 0.55
            fine = rnd.uniform(-amp * 0.3, amp * 0.3)
            bite = -rnd.uniform(amp * 0.8, amp * 1.9) if rnd.random() < 0.08 else 0.0
            off = wander + swell + fine + bite
            pts.append((x0 + ux * t + nx * off, y0 + uy * t + ny * off))
    return "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + " Z"

# viewBox 1440 x 1000, anchored to the bottom of the hero.
# Every fragment starts below y=360 so nothing sits behind the headline, and
# each one bleeds past at least one edge so they read as large sheets rather
# than as floating shapes.
FRAGS = [
    # muted burgundy — the broadest sheet, bleeding left and bottom
    ("SLAB", torn_quad([(-180, 430), (1210, 345), (1300, 1080), (-150, 1120)], 11, amp=34, step=30)),
    # deeper layer offset to the right, bleeding right and bottom
    ("DEEP", torn_quad([(360, 520), (1520, 430), (1560, 1090), (400, 1130)], 5, amp=27, step=26)),
    # a corner of cream stock, bottom left and mostly off-canvas: a hint of the
    # paper the cut-out was torn from. Sits BELOW the copy block — an earlier
    # version ran up the left edge and put ivory text on cream.
    ("CREAM", torn_quad([(-140, 845), (105, 820), (140, 1120), (-120, 1140)], 23, amp=17, step=19)),
]

tsx = '''/* ---------------------------------------------------------------------------
 * PAPER COLLAGE
 *
 * The torn paper layers behind the hero cut-out: a broad muted burgundy sheet,
 * a deeper layer offset to the right, and a narrow strip of cream stock at the
 * far left. Generated by scripts/fragments.py — edit there, not here.
 *
 * Two rules drive the placement. Every fragment starts below the headline, so
 * nothing sits behind the type. And the large fragments are dark, because the
 * cut-out carries its own cream torn edge — a big cream shape behind her would
 * swallow it and lose the subject.
 * -------------------------------------------------------------------------*/
import { cn } from "@/lib/utils";

export function PaperCollage({ className }: { className?: string }) {
  return (
    <svg
      aria-hidden
      viewBox="0 0 1440 1000"
      preserveAspectRatio="xMidYMax slice"
      className={cn("pointer-events-none absolute inset-0 size-full", className)}
    >
      <defs>
        {/* Vintage stock grain. Applied only to the small cream corner —
            filtering a full-bleed path costs ~200ms of style and layout on a
            throttled phone, and on the dark layers the grain is invisible
            anyway. */}
        <filter id="paper-grain" x="-5%" y="-5%" width="110%" height="110%">
          <feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="3" seed="7" />
          <feColorMatrix
            type="matrix"
            values="0 0 0 0 0.52
                    0 0 0 0 0.46
                    0 0 0 0 0.38
                    0 0 0 0.42 0"
          />
        </filter>
      </defs>

      <path d="SLAB_D" fill="var(--color-burgundy)" opacity="0.5" />

      <path d="DEEP_D" fill="var(--color-navy-sunken)" opacity="0.72" />

      {/* The cream corner is desktop-only: at narrow widths the viewBox
          crops to the centre and it would land under the copy. */}
      <path d="CREAM_D" fill="#e9dcc6" opacity="0.9" className="hidden lg:block" />
      <path d="CREAM_D" filter="url(#paper-grain)" opacity="0.55" className="hidden lg:block" />
    </svg>
  );
}
'''
for key, d in FRAGS:
    tsx = tsx.replace(key + "_D", d)
open("components/ui/PaperCollage.tsx", "w").write(tsx)
print("PaperCollage regenerated:", {k: len(v) for k, v in FRAGS})
